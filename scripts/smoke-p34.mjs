import assert from "node:assert/strict";
import { mkdtempSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
const root = mkdtempSync(join(tmpdir(), "dsh-cost-p34-"));
process.env.DSH_HOME = join(root, "home"); process.env.DSH_TRIVIUM_SETTINGS = join(root, "settings.json");
const store = await import("../lib/store.js");
const { distill, ruleCandidates } = await import("../lib/extract.js");
const { registerTools } = await import("../lib/tools.js");
const tools = new Map(); registerTools({ effect: (f) => f(), tools: { register: (t) => { tools.set(t.name, t); return () => {}; } }, on() {} }, {});
try {
  assert.ok(!ruleCandidates([{ role: "user", text: "采用方案 BluePlan，先验证兼容性。" }]).some((r) => r.type === "entity" && r.name === "方案 B"), "a multi-letter name is not a one-letter plan");
  assert.ok(ruleCandidates([{ role: "user", text: "采用方案 B，先验证兼容性。" }]).some((r) => r.type === "entity" && r.name === "方案 B"), "the actual one-letter plan still works");
  const cwd = join(root, "workspace"), db = await store.openWorkspaceDb(cwd);
  let calls = 0;
  const llmCall = async () => { calls++; return '{"candidates":[]}'; };
  await distill({ db, turns: [{ role: "user", text: "谢谢！" }, { role: "assistant", text: "好的。" }], llmCall });
  assert.equal(calls, 0, "pure acknowledgements need no model");
  for (const turns of [[{ role: "user", text: "以后发布都先验收" }], [{ role: "user", text: "这个项目的数据库是 QuasarStore" }], [{ role: "tool", text: "failure", ok: false }]]) await distill({ db, turns, llmCall });
  assert.equal(calls, 3, "explicit, implicit and tool evidence still reach the model");
  const toolOnly = await distill({ db, turns: [{ role: "tool", name: "compile", turn: 9, ok: false, text: "" }, { role: "tool", name: "compile", turn: 9, ok: true, text: "" }], llmCall });
  assert.ok(toolOnly.applied.some((x) => x.type === "experience"), "empty tool text still carries failure/success evidence");
  const entity = store.insertNode(db, { type: "entity", name: "AuroraService", text: "AuroraService" });
  const id = store.insertNode(db, { type: "decision", name: "验收约定", text: "AuroraService 必须跑验收脚本。" });
  store.ensureLink(db, id, entity, "about");
  const hit = { id, score: 1 };
  assert.ok(store.formatHit(db, hit).path.some((p) => p.includes("in_workspace")), "management path remains available");
  const model = store.formatHit(db, hit, { includeWorkspace: false });
  assert.ok(model.path.some((p) => p.includes("about")));
  assert.ok(model.path.every((p) => !p.includes("in_workspace")));
  const exec = { agent: { session: { header: { cwd } } } };
  const found = String(await tools.get("ctx_find").execute({ query: "验收约定" }, exec));
  assert.match(found, /必须跑验收/); assert.match(found, /about/); assert.doesNotMatch(found, /in_workspace|path: \(none\)/);
  const full = String(await tools.get("ctx_read").execute({ id }, exec));
  assert.equal(JSON.parse(full).payload.text, "AuroraService 必须跑验收脚本。");
  assert.ok(JSON.parse(full).edges.length >= 2, "explicit read still returns all edges");
  assert.equal(full, JSON.stringify(JSON.parse(full)), "compact serialization changes no JSON fields");
  console.log("P34 cost guards passed: acknowledgements only, implicit/tool facts retained, business paths and full read preserved");
} finally { store.closeAll(); rmSync(root, { recursive: true, force: true }); }
